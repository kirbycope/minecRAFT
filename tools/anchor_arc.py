"""Writes the Throwable Anchor's throw into the data pack as world/datapacks/raft/data/raft/function/anchor/generated/arc.mcfunction.

The throw is the same as minecRAFT-bedrock's anchor.js: 12 ticks of arc out to THROW_OUT blocks off the side it was
set down on, rising 1.5 blocks and landing 1.2 below where it started, then 30 ticks sinking to SINK_TO. The function
runs as the anchor, positioned at the middle of the post half a block up and rotated to face the throw, so each tick
is one teleport in local coordinates (^ ^up ^forward).

    python tools/anchor_arc.py
"""

import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "world", "datapacks", "raft", "data", "raft", "function", "anchor", "generated", "arc.mcfunction")
THROW_OUT = 3.0     # how far from the post the anchor lands, in blocks
POST_Y = 106.5      # where the throw starts: the middle of a post on the raft
SINK_TO = 102.0     # world y the anchor settles at, under the raft's water, in reach of its lead
FLIGHT_TICKS = 12
SINK_TICKS = 30


def main() -> None:
    lines = ["# Generated by tools/anchor_arc.py: the anchor's throw, a tick a line. Do not edit by hand."]
    for tick in range(1, FLIGHT_TICKS + SINK_TICKS + 1):
        if tick <= FLIGHT_TICKS:
            t = tick / FLIGHT_TICKS
            forward, up = THROW_OUT * t, math.sin(t * math.pi) * 1.5 - t * 1.2
        else:
            t = (tick - FLIGHT_TICKS) / SINK_TICKS
            forward, up = THROW_OUT, -1.2 + (SINK_TO - POST_Y + 1.2) * t
        lines.append(f"execute if score #throw raft.state matches {tick} run tp @s ^ ^{up:.3f} ^{forward:.3f}")
        if tick == FLIGHT_TICKS:
            lines.append(f"execute if score #throw raft.state matches {tick} positioned ^ ^ ^{forward:.3f} run "
                         "playsound minecraft:entity.generic.splash neutral @a ~ ~ ~ 1 1")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
